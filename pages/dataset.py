import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt

def render():
    st.title("Dataset Introduction: 140K Real and Fake Faces")
    
    st.markdown("""
    This project uses the public dataset **“140K Real and Fake Faces”** by Xhlulu on Kaggle.  Source: [Kaggle Dataset](https://www.kaggle.com/datasets/xhlulu/140k-real-and-fake-faces)
    """)
    
    # ---- a) Dataset Overview ----
    st.header("Dataset Overview")
    st.markdown("""
    The dataset contains **140,000 face images**, evenly split into two groups:
    - **Real** – real images of human faces.
    - **Fake** – synthetic images generated by a **GAN (StyleGAN v2)** using *ThisPersonDoesNotExist.com*.
    
    Each image is a single, centered, high-quality face, suitable for training and evaluating deepfake detection models.
    """)
    
    # ---- b) Dataset Features ----
    st.header("Dataset Features")
    data_features = {
        "Attribute": ["Total Images", "Image Size", "File Format", "Number of Classes", "Source of Fake Images", "Compressed Size"],
        "Description": ["140,000 images", "256 × 256 pixels", "JPEG (.jpg)", "2 classes: Real and Fake", "GAN (StyleGAN v2)", "~2.1 GB"]
    }
    df_features = pd.DataFrame(data_features)
    st.table(df_features)
    
    st.markdown("""
    Images are standardized in size and layout, allowing models to focus on detecting **micro-artifacts** rather than image preprocessing.
    """)

    # ---- c) Data Splits ----
    st.header("Data Splits")
    split_data = {
        "Dataset": ["Train", "Validation", "Test"],
        "Proportion": ["~70%", "~15%", "~15%"],
        "Purpose": ["Model training", "Hyperparameter tuning / prevent overfitting", "Final evaluation"],
        "Estimated Samples": ["~100,000 images", "~20,000 images", "~20,000 images"]
    }
    df_split = pd.DataFrame(split_data)
    st.table(df_split)
    st.markdown("Each split is balanced between Real and Fake classes.")
   
    # Số lượng giả lập, cân bằng giữa Real / Fake
    split_counts = {
        "Train": {"Real": 50000, "Fake": 50000},
        "Validation": {"Real": 10000, "Fake": 10000},
        "Test": {"Real": 10000, "Fake": 10000}
    }
    
    # Vẽ biểu đồ
    splits = list(split_counts.keys())
    real_counts = [split_counts[s]["Real"] for s in splits]
    fake_counts = [split_counts[s]["Fake"] for s in splits]
    
    x = range(len(splits))
    width = 0.3
    
    fig, ax = plt.subplots(figsize=(5,3))
    ax.bar([i - width/2 for i in x], real_counts, width, label='Real', color='skyblue')
    ax.bar([i + width/2 for i in x], fake_counts, width, label='Fake', color='salmon')
    
    ax.set_xticks(x)
    ax.set_xticklabels(splits)
    ax.set_ylabel("Number of Images")
    ax.set_title("Distribution of Real and Fake Images per Split")
    ax.legend()
    
    st.pyplot(fig)
    
    # ---- d) Detailed Dataset Attributes ----
    st.header("Detailed Dataset Attributes")
    detailed_features = {
        "Attribute": ["File Format", "Image Size", "Color Channels", "Number of Classes", "Total Images", "Compressed Size"],
        "Description": ["JPEG (.jpg)", "256 × 256 pixels", "RGB (3 channels)", "2 classes: Real and Fake", "Approximately 140,000 images", "4.04 GB"]
    }
    df_detailed = pd.DataFrame(detailed_features)
    st.table(df_detailed)
    
    st.markdown("""
    Fake images are generated using **StyleGAN**, often exhibiting artifacts around eyes, hair, background blur, or lighting inconsistencies, which models can learn to distinguish from real images.
    """)
    
    # ---- References ----
    st.markdown("<h2 id='references' class='fade-in-section' style='color:#191970;'>References</h2>", unsafe_allow_html=True)
    st.markdown("""
    <div class="ref-box" style="background-color:#e6f2ff; padding:15px; border-radius:10px;">
        <ul>
            <li>Xhlulu. (2021). 140K Real and Fake Faces. <i>Kaggle Dataset</i>. <a href="https://www.kaggle.com/datasets/xhlulu/140k-real-and-fake-faces" target="_blank">140K Real and Fake Faces</a></li>
        </ul>
    </div>
    """, unsafe_allow_html=True)